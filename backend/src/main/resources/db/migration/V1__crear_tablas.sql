-- TecnoUAM: esquema inicial (equipos y préstamos)
--CREATE DATABASE tecnouam;

CREATE TABLE equipos (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_patrimonial VARCHAR(50)  NOT NULL,
    nombre             VARCHAR(120) NOT NULL,
    tipo               VARCHAR(60)  NOT NULL,
    estado             VARCHAR(20)  NOT NULL DEFAULT 'DISPONIBLE',
    CONSTRAINT uk_equipos_codigo_patrimonial UNIQUE (codigo_patrimonial),
    CONSTRAINT ck_equipos_estado CHECK (estado IN ('DISPONIBLE', 'PRESTADO'))
);

CREATE TABLE prestamos (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipo_id                 BIGINT       NOT NULL,
    nombre_solicitante        VARCHAR(120) NOT NULL,
    fecha_prestamo            DATE         NOT NULL,
    fecha_prevista_devolucion DATE         NOT NULL,
    fecha_devolucion_real     DATE,
    estado                    VARCHAR(20)  NOT NULL DEFAULT 'ACTIVO',
    -- Si se borra un equipo (el servicio ya bloqueó los que tienen préstamo
    -- ACTIVO), su historial de préstamos DEVUELTOS se elimina con él.
    CONSTRAINT fk_prestamos_equipo FOREIGN KEY (equipo_id)
        REFERENCES equipos (id) ON DELETE CASCADE,
    CONSTRAINT ck_prestamos_estado CHECK (estado IN ('ACTIVO', 'DEVUELTO')),
    CONSTRAINT ck_prestamos_fechas CHECK (fecha_prevista_devolucion >= fecha_prestamo)
);

CREATE INDEX idx_prestamos_equipo_id ON prestamos (equipo_id);
CREATE INDEX idx_prestamos_estado ON prestamos (estado);

-- Regla de negocio a nivel de base de datos: un equipo no puede tener
-- dos préstamos ACTIVOS al mismo tiempo (protege incluso ante peticiones
-- simultáneas).
CREATE UNIQUE INDEX ux_prestamos_un_activo_por_equipo
    ON prestamos (equipo_id)
    WHERE estado = 'ACTIVO';
